export function formatStudyDate(value: string) {
  return new Intl.DateTimeFormat("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(value));
}

export function getStudyById(id: string) {
  return DEMO_STUDIES.find((study) => study.id === id);
}

export function filterStudies(studies: StudyRecord[], query: string) {
  const normalized = query.trim().toLowerCase();

  if (!normalized) {
    return studies;
  }

  return studies.filter(
    (study) =>
      study.id.toLowerCase().includes(normalized) ||
      study.patientName.toLowerCase().includes(normalized),
  );
}
